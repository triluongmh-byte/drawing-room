// Copies the Lucide icons the UI uses into static/js/icons.js, so the app ships them and never fetches any.
// Run `npm run build:icons` after adding a name below.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "node_modules", "lucide-static", "icons");
const target = join(root, "src", "drawing_room", "static", "js", "icons.js");

const NAMES = [
  "pencil", "pen-tool", "pen", "paintbrush", "brush", "highlighter", "eraser", "ruler",
  "undo-2", "redo-2", "rotate-ccw", "rotate-cw", "scan", "brush-cleaning", "trash-2",
  "image", "layers", "target", "message-circle", "folder", "chevron-down", "plus", "eye", "eye-off",
  "lock", "lock-open", "star", "chevron-left", "chevron-right", "x", "upload", "send", "check",
  "dumbbell", "route", "scan-line", "graduation-cap", "file", "eraser",
  "paperclip", "grid-3x3", "map-pin-plus", "shapes", "slash", "square", "circle", "triangle", "diamond", "arrow-up-right",
];

const icons = {};
for (const name of new Set(NAMES)) {
  const svg = readFileSync(join(source, `${name}.svg`), "utf8");
  // Keep only the drawing: the <svg> wrapper is written by icon() so every icon gets the same attributes.
  icons[name] = svg.replace(/<!--.*?-->/gs, "").replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "")
    .replace(/\s*\n\s*/g, "").trim();
}

const version = JSON.parse(readFileSync(join(source, "..", "package.json"), "utf8")).version;
writeFileSync(target, `// Generated by scripts/build-icons.mjs from lucide-static ${version} (ISC, see ../vendor/lucide.LICENSE). Do not edit.

const ICONS = ${JSON.stringify(icons, null, 2)};

/** An inline Lucide icon as SVG markup; \`size\` in CSS pixels. Unknown names give an empty string. */
export function icon(name, size = 18) {
  const body = ICONS[name];
  if (!body) return "";
  return \`<svg class="icon" xmlns="http://www.w3.org/2000/svg" width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">\${body}</svg>\`;
}

/** Fill every \`<i data-icon="name">\` in the page with its icon. */
export function hydrateIcons(root = document) {
  for (const el of root.querySelectorAll("i[data-icon]")) {
    if (!el.firstChild) el.innerHTML = icon(el.dataset.icon, Number(el.dataset.size) || 18);
  }
}
`);
console.log(`icons.js: ${Object.keys(icons).length} icons`);
